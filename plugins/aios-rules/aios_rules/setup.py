"""Set up a member's folder and rules without overwriting anything that already exists."""
from pathlib import Path

from . import frontmatter

TEMPLATES = Path(__file__).resolve().parents[1] / 'templates'
FOLDERS = ['00_inbox', '10_clients', '20_offers', '30_finance', '40_content', '50_projects', '80_aios', '90_archive']
RULES = ['clients.md', 'finance.md', 'content.md']
GENERATED = '<!-- generated by aios-rules from %s; edit that file, then run: aios-rules cursor-rules -->'


def has_bridge(text):
    for line in (text or '').split('\n'):
        if line.strip() in ('@AGENTS.md', '@./AGENTS.md'):
            return True
    return False


def init(folder, business=None, owner=None, make_folders=True, dry_run=False):
    """Create what is missing. Returns a list of (action, path, note) tuples."""
    folder = Path(folder).resolve()
    report = []

    def write(path, text, note):
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
        report.append(('created', path, note))

    if not dry_run:
        folder.mkdir(parents=True, exist_ok=True)
    if make_folders:
        for name in FOLDERS:
            path = folder / name
            if path.exists():
                report.append(('kept', path, 'folder already there'))
            else:
                if not dry_run:
                    path.mkdir(parents=True)
                report.append(('created', path, 'folder'))

    agents = folder / 'AGENTS.md'
    if agents.exists():
        report.append(('kept', agents, 'your rules file is unchanged; compare it with the starter in the pack'))
    else:
        text = (TEMPLATES / 'AGENTS.md').read_text(encoding='utf-8')
        if business:
            text = text.replace('{{BUSINESS}}', business)
        if owner:
            text = text.replace('{{OWNER}}', owner)
        write(agents, text, 'starter rules file: fill in the {{...}} lines')

    claude = folder / 'CLAUDE.md'
    if not claude.exists():
        write(claude, '@AGENTS.md\n', 'one-line bridge so Claude Code reads AGENTS.md')
    elif has_bridge(claude.read_text(encoding='utf-8', errors='replace')):
        report.append(('kept', claude, 'already imports AGENTS.md'))
    else:
        report.append(('action', claude, 'add the line @AGENTS.md at the top yourself; nothing was changed'))

    if (folder / 'CLAUDE.local.md').exists():
        report.append(('action', folder / 'CLAUDE.local.md',
                       'personal notes file found; keep @AGENTS.md in CLAUDE.md so Claude Code still reads AGENTS.md'))

    for name in RULES:
        path = folder / '.claude' / 'rules' / name
        if path.exists():
            report.append(('kept', path, 'rule already there'))
        else:
            write(path, (TEMPLATES / 'rules' / name).read_text(encoding='utf-8'), 'path-scoped rule')
    return report


def cursor_rules(folder, dry_run=False):
    """Mirror .claude/rules/*.md into .cursor/rules/*.mdc so Cursor gets the same scoped rules."""
    folder = Path(folder).resolve()
    source = folder / '.claude' / 'rules'
    report = []
    if not source.is_dir():
        return [('skipped', source, 'no .claude/rules folder')]
    for rule in sorted(p for p in source.rglob('*.md') if p.is_file()):
        relative = rule.relative_to(folder)
        block, body = frontmatter.split(rule.read_text(encoding='utf-8', errors='replace'))
        paths = frontmatter.as_list(frontmatter.parse(block).get('paths'))
        heading = next((l.lstrip('# ').strip() for l in body.split('\n') if l.startswith('#')), rule.stem)
        lines = ['---', 'description: ' + heading.replace(':', ' -')]
        if paths:
            lines += ['globs: ' + ','.join(paths), 'alwaysApply: false']
        else:
            lines += ['alwaysApply: true']
        lines += ['---', GENERATED % relative.as_posix(), body.lstrip('\n')]
        name = '-'.join(rule.relative_to(source).with_suffix('').parts) + '.mdc'
        target = folder / '.cursor' / 'rules' / name
        text = '\n'.join(lines)
        if target.exists() and 'generated by aios-rules' not in target.read_text(encoding='utf-8', errors='replace'):
            report.append(('kept', target, 'your own Cursor rule has this name; nothing was changed'))
            continue
        if not dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8')
        report.append(('written', target, 'from ' + relative.as_posix()))
    return report


def render(report, folder):
    folder = Path(folder).resolve()
    out = []
    for action, path, note in report:
        try:
            shown = './' + Path(path).relative_to(folder).as_posix()
        except ValueError:
            shown = str(path)
        out.append('%-8s %s  (%s)' % (action.upper(), shown, note))
    return '\n'.join(out) + '\n'


