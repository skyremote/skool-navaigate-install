SOURCES=('claude','codex','cursor')
ACTIVE_GRACE_SECONDS=120
CRASH_TAIL_SECONDS=300
_LEADING=re.compile(r'^\s*<(system-reminder|environment_context|command-name|command-message|command-args|local-command-stdout|local-command-stderr|user-prompt-submit-hook|bash-stdout|bash-stderr)>.*?</\1>\s*',re.S)
_CURSOR=re.compile(r'^\s*(?:<timestamp>(.*?)</timestamp>\s*)?<user_query>(.*?)</user_query>\s*$',re.S)


class SessionChanged(ValueError):
    pass


class IncompleteTail(ValueError):
    pass


def clean(text,source=None,role='user',text_export=False):
    if role=='user' and source in (None,'codex') and text.lstrip().startswith('# AGENTS.md instructions'):
        end=text.find('</INSTRUCTIONS>')
        text=text[end+len('</INSTRUCTIONS>'):] if end>=0 else ''
    if source=='cursor' and role=='user':
        wrapper=_CURSOR.fullmatch(text)
        if wrapper:
            text=wrapper[2]
    # Only known leading injected envelopes. Quoted/inline prompt examples survive.
    while True:
        stripped=_LEADING.sub('',text,count=1)
        if stripped==text:
            break
        text=stripped
    if source=='cursor' and text_export:
        text=re.split(r'(?m)^\[(?:Tool call|Tool result|Thinking)\]',text,maxsplit=1)[0]
    if text.startswith('Caveat: The messages below were generated by the user while running local commands'):
        text=text.partition('\n')[2]
    return redact(text.strip())


def text_blocks(value):
    if isinstance(value,str):
        return value
    if not isinstance(value,list):
        return ''
    return '\n'.join(v.get('text','') for v in value if isinstance(v,dict)
                     and v.get('type') in ('text','input_text','output_text'))


def epoch(value,fallback=0):
    if isinstance(value,(int,float)):
        return value/1000 if value>10**11 else float(value)
    if isinstance(value,str):
        try:
            parsed=datetime.fromisoformat(value.replace('Z','+00:00'))
            return parsed.replace(tzinfo=parsed.tzinfo or timezone.utc).timestamp()
        except ValueError:
            pass
    return fallback


def cursor_epoch(text):
    wrapper=_CURSOR.fullmatch(text)
    if not wrapper or not wrapper[1]:
        return 0
    raw=wrapper[1].strip()
    iso=epoch(raw)
    if iso:
        return iso
    match=re.fullmatch(r'(.*?)\s*\(UTC([+-]\d{1,2})(?::(\d{2}))?\)',raw)
    try:
        core=match[1] if match else raw
        value=datetime.strptime(core.strip(),'%A, %b %d, %Y, %I:%M %p')
        minutes=(abs(int(match[2]))*60+int(match[3] or 0))*(1 if int(match[2])>=0 else -1) if match else 0
        return value.replace(tzinfo=timezone(timedelta(minutes=minutes))).timestamp()
    except (ValueError,TypeError):
        return 0


def config_dirs():
    home=Path.home()
    return {'claude':Path(os.environ.get('CLAUDE_CONFIG_DIR') or home/'.claude').expanduser(),
            'codex':Path(os.environ.get('CODEX_HOME') or home/'.codex').expanduser(),
            'cursor':home/'.cursor'}


def roots():
    dirs=config_dirs()
    return {'claude':[dirs['claude']/'projects'],
            'codex':[dirs['codex']/'sessions',dirs['codex']/'archived_sessions'],
            'cursor':[dirs['cursor']/'projects']}


def installed_sources():
    # Merely linking a pack into .cursor/skills does not install the Cursor app.
    found=[]
    overrides={'claude':'CLAUDE_CONFIG_DIR','codex':'CODEX_HOME'}
    for name,path in config_dirs().items():
        explicit=bool(os.environ.get(overrides.get(name,''))) and path.is_dir()
        if shutil.which(name) or explicit or any(root.is_dir() for root in roots()[name]):
            found.append(name)
    return found


def files():
    for source,dirs in roots().items():
        for root in dirs:
            if not root.exists():
                continue
            for path in sorted(root.rglob('*')):
                if not path.is_file() or path.suffix not in ('.jsonl','.txt'):
                    continue
                if source!='cursor' and path.suffix!='.jsonl':
                    continue
                if source=='cursor' and 'agent-transcripts' not in path.parts:
                    continue
                if 'subagents' in path.parts or path.name.startswith('agent-'):
                    continue
                yield source,path


def fingerprint(path):
    before=path.stat()
    digest=hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda:stream.read(1024*1024),b''):
            digest.update(block)
    after=path.stat()
    if (before.st_mtime_ns,before.st_size)!=(after.st_mtime_ns,after.st_size):
        raise SessionChanged('Session changed during inspection; retry capture')
    return digest.hexdigest(),after


def _with_last(lines):
    previous=None
    for n,line in enumerate(lines,1):
        if not line.strip():
            continue
        if previous is not None:
            yield previous[0],previous[1],False
        previous=(n,line)
    if previous is not None:
        yield previous[0],previous[1],True


class Session:
    def __init__(self,source,path,modified):
        self.source,self.path,self.modified=source,path,modified
        self.sid,self.meta_seen,self.subagent=path.stem,False,False
        self.warnings=[]
        self.latest=0

    def turns(self,lines):
        if self.source=='cursor' and self.path.suffix=='.txt':
            role,parts,seen=None,[],False
            for line in lines:
                marker=re.fullmatch(r'(user|assistant):\s*',line.strip())
                if marker:
                    if role:
                        body=clean(''.join(parts),'cursor',role,True)
                        if body:
                            yield role,body,0.0
                    role,parts,seen=marker[1],[],True
                elif role:
                    parts.append(line)
            if role:
                body=clean(''.join(parts),'cursor',role,True)
                if body:
                    yield role,body,0.0
            if not seen:
                raise ValueError('Unrecognised Cursor transcript; export role-labelled text or JSONL')
            return
        cursor_time=0
        for n,line,last in _with_last(lines):
            try:
                event=json.loads(line)
                if not isinstance(event,dict):
                    raise ValueError('Expected an object')
            except ValueError:
                if last:
                    if time.time()-self.modified>=CRASH_TAIL_SECONDS:
                        self.warnings.append(f'{self.path.name}: recovered valid turns; skipped an incomplete final line after 5 minutes idle')
                        break
                    raise IncompleteTail('Incomplete final session line; retry after the writer finishes') from None
                raise ValueError(f'Malformed session JSON at line {n}; valid turns were not marked complete') from None
            msg=None
            ts=epoch(event.get('timestamp'))
            if self.source=='codex':
                payload=event.get('payload') or {}
                if not isinstance(payload,dict):
                    raise ValueError(f'Malformed Codex event at line {n}')
                if event.get('type')=='session_meta' and not self.meta_seen:
                    self.meta_seen=True
                    origin=payload.get('source') or {}
                    if payload.get('thread_source')=='subagent' or isinstance(origin,dict) and 'subagent' in origin:
                        self.subagent=True
                        return
                    self.sid=payload.get('id') or self.sid
                elif event.get('type')=='response_item' and payload.get('type')=='message' and payload.get('channel')!='analysis':
                    msg=payload
            elif self.source=='claude':
                if event.get('isSidechain'):
                    continue
                if not self.meta_seen and event.get('sessionId'):
                    self.sid,self.meta_seen=event['sessionId'],True
                msg=event.get('message')
            elif event.get('role') in ('user','assistant'):
                nested=event.get('message') or {}
                if not isinstance(nested,dict):
                    raise ValueError(f'Malformed Cursor event at line {n}')
                msg={'role':event['role'],'content':nested.get('content',event.get('content'))}
                raw=text_blocks(msg['content'])
                embedded=cursor_epoch(raw) if msg['role']=='user' else 0
                cursor_time=embedded or ts or cursor_time
                ts=embedded or ts or cursor_time  # Unknown times remain zero, never file mtime.
            if isinstance(msg,dict) and msg.get('role') in ('user','assistant'):
                body=clean(text_blocks(msg.get('content')),self.source,msg['role'])
                if body:
                    self.latest=max(self.latest,ts)
                    yield msg['role'],body,float(ts)


def parse(source,path,raw,modified):
    """Compatibility helper for small fixtures; runtime capture uses line streams."""
    session=Session(source,path,modified)
    messages=list(session.turns(io.StringIO(raw.decode('utf-8')) if path.suffix=='.txt' else io.BytesIO(raw)))
    return (None if session.subagent else str(session.sid)),messages


def message_hash(turns):
    digest=hashlib.sha256()
    for turn in turns:
        digest.update(db.serialise([turn[0],turn[1],float(turn[2])]).encode())
        digest.update(b'\n')
    return digest.hexdigest()


def stored_turns(conn,ref):
    return (tuple(row) for row in conn.execute("SELECT role,body,ts FROM documents WHERE ref=? AND kind='message' ORDER BY id",(ref,)))


def save_state(conn,path,ref,stat,digest,turn_hash,warnings):
    with conn:
        conn.execute('INSERT OR REPLACE INTO file_state VALUES(?,?,?,?,?,?,?)',
                     (str(path),ref,stat.st_size,stat.st_mtime_ns,digest,turn_hash,json.dumps(warnings)))
        conn.execute('DELETE FROM health_pending WHERE path=?',(str(path),))


def capture(conn):
    result={'captured':0,'unchanged':0,'messages':0,'skipped_subagents':0,'failures':[],'warnings':[]}
    local=db.device(conn)
    db.prune_failures(conn)
    try:
        candidates=list(files())
    except OSError:
        db.failure(conn,'discovery','Cannot read a session folder; check permissions')
        raise ValueError('Cannot read a session folder; check permissions') from None
    db.clear_failure(conn,'discovery')
    for source,path in candidates:
        scope='capture:'+str(path)
        try:
            digest,stat=fingerprint(path)
            old=conn.execute('SELECT * FROM items WHERE device=? AND path=?',(local,str(path))).fetchone()
            cache=conn.execute('SELECT * FROM file_state WHERE path=?',(str(path),)).fetchone()
            if old and cache and old['file_hash']==digest and cache['message_hash']==message_hash(stored_turns(conn,old['ref'])):
                result['unchanged']+=1
                warnings=json.loads(cache['warnings'])
                result['warnings'].extend(warnings)
                save_state(conn,path,old['ref'],stat,digest,cache['message_hash'],warnings)
                db.clear_failure(conn,scope)
                continue
            session=Session(source,path,stat.st_mtime)
            with (path.open(encoding='utf-8') if path.suffix=='.txt' else path.open('rb')) as stream:
                messages=list(session.turns(stream))
            if path.stat().st_mtime_ns!=stat.st_mtime_ns or path.stat().st_size!=stat.st_size:
                raise ValueError('Session changed during capture; retry brain capture')
            if session.subagent:
                result['skipped_subagents']+=1
                db.clear_failure(conn,scope)
                continue
            ref=f'{source}:{local}:{session.sid}'
            if old and old['ref']!=ref:
                raise ValueError('Session identity changed in place; preserve the old file and investigate')
            duplicate=conn.execute('SELECT path FROM items WHERE ref=?',(ref,)).fetchone()
            if duplicate and duplicate['path']!=str(path) and duplicate['path'] and Path(duplicate['path']).exists() and old is None:
                raise ValueError('Duplicate session identity in two files; keep one session copy')
            previous=db.bundle(conn,ref) if duplicate else None
            docs=[{'id':f'{ref}:{n:08d}','kind':'message','role':role,'body':body,'ts':ts}
                  for n,(role,body,ts) in enumerate(messages)]
            if previous and previous['item']['digest']:
                session.warnings.append(path.name+': saved digest predates the changed session; run brain digest '+ref+' to refresh it')
            if previous:
                docs.extend(d for d in previous['documents'] if d['kind']=='digest')
            item={'ref':ref,'source':source,'device':local,'path':str(path),'file_hash':digest,
                  'modified':stat.st_mtime,'latest':session.latest,'updated':db.next_version(previous['item']['updated'] if previous else 0),
                  'title':previous['item']['title'] if previous else '',
                  'url':None,'digest':previous['item']['digest'] if previous else None}
            db.put_item(conn,item,docs)
            save_state(conn,path,ref,stat,digest,message_hash(messages),session.warnings)
            db.clear_failure(conn,scope)
            result['captured']+=1
            result['messages']+=len(messages)
            result['warnings'].extend(session.warnings)
        except IncompleteTail as exc:
            if old:
                result.setdefault('active_files',[]).append(path.name)
                db.clear_failure(conn,scope)
            else:
                error=f'{path.name}: {exc}'
                db.failure(conn,scope,error)
                result['failures'].append(error)
        except (OSError,ValueError,UnicodeError) as exc:
            error=redact(f'{path.name}: {exc}')
            db.failure(conn,scope,error)
            result['failures'].append(error)
    return result
